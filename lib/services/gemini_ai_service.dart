/// Representation of a song recommended by Gemini AI
class AiSongRecommendation {
  final String title;
  final String artist;
  final String vibe;

  const AiSongRecommendation({
    required this.title,
    required this.artist,
    this.vibe = '',
  });

  factory AiSongRecommendation.fromJson(Map<String, dynamic> json) {
    return AiSongRecommendation(
      title: json['title']?.toString() ?? '',
      artist: json['artist']?.toString() ?? '',
      vibe: json['vibe']?.toString() ?? '',
    );
  }
}

/// Rich musical and emotional insights for a song generated by Gemini
class SongAiInsight {
  final String songTitle;
  final String artist;
  final String mood;
  final String energyLevel;
  final String story;
  final String listeningContext;
  final List<String> similarArtists;

  const SongAiInsight({
    required this.songTitle,
    required this.artist,
    required this.mood,
    required this.energyLevel,
    required this.story,
    required this.listeningContext,
    required this.similarArtists,
  });

  factory SongAiInsight.fallback(Song song) {
    return SongAiInsight(
      songTitle: song.title,
      artist: song.artist,
      mood: 'Melodic & Atmospheric',
      energyLevel: 'Balanced',
      story:
          '"${song.title}" by ${song.artist} delivers an evocative musical expression blending memorable melodies with heartfelt emotion.',
      listeningContext: 'Anytime you want to immerse yourself in great music.',
      similarArtists: [song.artist, 'Top Chart Artists'],
    );
  }
}

class GeminiAiService {
  static final GeminiAiService instance = GeminiAiService._internal();
  GeminiAiService._internal();
  factory GeminiAiService() => instance;

  // In-memory cache for insights to minimize API calls
  final Map<String, SongAiInsight> _insightCache = {};

  /// Calls Gemini REST API to generate structured content
  Future<String?> _callGemini(String prompt) async {
    final apiKey = AppConfig.geminiApiKey;
    if (apiKey.isEmpty) {
      debugPrint('[GeminiAiService] No API key configured');
      return null;
    }

    // List of candidate models in order of capability
    final models = [
      'gemini-3.7-flash',
      'gemini-3.5-flash-lite',
      'gemini-2.5-flash',
      'gemini-flash-latest',
    ];

    for (final model in models) {
      try {
        final uri = Uri.parse(
          'https://generativelanguage.googleapis.com/v1beta/models/$model:generateContent?key=$apiKey',
        );

        final response = await http
            .post(
              uri,
              headers: {'Content-Type': 'application/json'},
              body: jsonEncode({
                'contents': [
                  {
                    'parts': [
                      {'text': prompt},
                    ],
                  },
                ],
                'generationConfig': {
                  'temperature': 0.7,
                  'maxOutputTokens': 1024,
                },
              }),
            )
            .timeout(const Duration(seconds: 12));

        if (response.statusCode == 200) {
          final data = jsonDecode(response.body);
          final candidates = data['candidates'] as List?;
          if (candidates != null && candidates.isNotEmpty) {
            final content = candidates[0]['content'];
            final parts = content?['parts'] as List?;
            if (parts != null && parts.isNotEmpty) {
              return parts[0]['text'] as String?;
            }
          }
        } else {
          debugPrint(
            '[GeminiAiService] Model $model status: ${response.statusCode} - ${response.body}',
          );
        }
      } catch (e) {
        debugPrint('[GeminiAiService] Model $model failed: $e');
        CrashReportingService.swallow(e, 'gemini_ai_service.dart:callGemini');
      }
    }
    return null;
  }

  /// Extracts JSON array or object from Gemini response text
  dynamic _extractJson(String text) {
    try {
      final cleanText = text.trim();
      // Look for ```json ... ``` or raw JSON
      final jsonBlockRegex = RegExp(r'```(?:json)?\s*([\s\S]*?)\s*```');
      final match = jsonBlockRegex.firstMatch(cleanText);
      final raw = match != null ? match.group(1)! : cleanText;

      final startBracket = raw.indexOf('[');
      final startBrace = raw.indexOf('{');

      if (startBracket != -1 && (startBrace == -1 || startBracket < startBrace)) {
        final endBracket = raw.lastIndexOf(']');
        if (endBracket != -1 && endBracket > startBracket) {
          return jsonDecode(raw.substring(startBracket, endBracket + 1));
        }
      } else if (startBrace != -1) {
        final endBrace = raw.lastIndexOf('}');
        if (endBrace != -1 && endBrace > startBrace) {
          return jsonDecode(raw.substring(startBrace, endBrace + 1));
        }
      }
      return jsonDecode(raw);
    } catch (e) {
      debugPrint('[GeminiAiService] JSON extraction error: $e');
      return null;
    }
  }

  /// Generates a curated list of songs from Gemini based on user mood/theme prompt
  Future<List<AiSongRecommendation>> generateRecommendations({
    required String prompt,
    int count = 8,
  }) async {
    final systemPrompt = '''
You are the AI Music Curator for "Jumbo Music", an Indian and international high-fidelity streaming app.
Based on the user's music vibe/request: "$prompt", generate a list of $count distinct, popular, and high-vibe songs.
Blend well-known popular hits with beloved gems that match the vibe accurately (Bollywood, Punjabi, Indie, English Pop, Hip-Hop, etc. as appropriate).

Return ONLY a strict JSON array of objects with keys "title", "artist", and "vibe". No markdown formatting around it if possible.
Example format:
[
  {"title": "Kesariya", "artist": "Arijit Singh", "vibe": "Soulful Romantic"},
  {"title": "Pee Loon", "artist": "Mohit Chauhan", "vibe": "Monsoon Love"}
]
''';

    final text = await _callGemini(systemPrompt);
    if (text != null) {
      final parsed = _extractJson(text);
      if (parsed is List) {
        final list = <AiSongRecommendation>[];
        for (final item in parsed) {
          if (item is Map<String, dynamic>) {
            final rec = AiSongRecommendation.fromJson(item);
            if (rec.title.isNotEmpty) {
              list.add(rec);
            }
          }
        }
        if (list.isNotEmpty) return list;
      }
    }

    // Fallback recommendations if AI service is temporarily offline
    return _getFallbackRecommendations(prompt);
  }

  /// Generates recommendations and resolves them into playable Song models
  Future<List<Song>> generatePlayableSongs({
    required String prompt,
    int count = 8,
  }) async {
    final recs = await generateRecommendations(prompt: prompt, count: count);
    final playableSongs = <Song>[];
    final Set<String> seenIds = {};

    // Concurrently search for the recommended tracks
    final searchFutures = recs.take(count).map((rec) async {
      try {
        final results = await MusicApiService.searchLiveSongs(
          '${rec.title} ${rec.artist}',
          limit: 3,
        );
        if (results.isNotEmpty) {
          return results.first;
        }
      } catch (e) {
        debugPrint('[GeminiAiService] Song lookup failed for ${rec.title}: $e');
      }
      return null;
    });

    final results = await Future.wait(searchFutures);
    for (final song in results) {
      if (song != null && seenIds.add(song.id)) {
        playableSongs.add(song);
      }
    }

    // If some tracks weren't found, fall back to searching the prompt directly
    if (playableSongs.length < 3) {
      try {
        final generic = await MusicApiService.searchLiveSongs(prompt, limit: 10);
        for (final s in generic) {
          if (seenIds.add(s.id)) {
            playableSongs.add(s);
          }
        }
      } catch (_) {}
    }

    return playableSongs;
  }

  /// Generates deep musical and lyrical insights for a specific song
  Future<SongAiInsight> getSongInsights(Song song) async {
    final cacheKey = '${song.title}_${song.artist}'.toLowerCase().trim();
    if (_insightCache.containsKey(cacheKey)) {
      return _insightCache[cacheKey]!;
    }

    final prompt = '''
Analyze the song "${song.title}" by "${song.artist}".
Provide rich musical and emotional insights in JSON format:
{
  "mood": "2 to 3 words describing the emotional mood (e.g. Melancholic, Euphoric, Nostalgic)",
  "energyLevel": "One of: Chill, Mellow, Uplifting, High-Energy, Intense",
  "story": "2 sentences describing the core meaning, lyrical emotion, and why listeners resonate with it.",
  "listeningContext": "Ideal setting to listen to this (e.g. Late night drive, Rain outside with chai, Gym workout, Deep focus).",
  "similarArtists": ["Artist 1", "Artist 2", "Artist 3"]
}
''';

    final text = await _callGemini(prompt);
    if (text != null) {
      final parsed = _extractJson(text);
      if (parsed is Map<String, dynamic>) {
        final insight = SongAiInsight(
          songTitle: song.title,
          artist: song.artist,
          mood: parsed['mood']?.toString() ?? 'Soulful & Melodic',
          energyLevel: parsed['energyLevel']?.toString() ?? 'Uplifting',
          story: parsed['story']?.toString() ??
              '"${song.title}" delivers an emotional narrative wrapped in memorable rhythms.',
          listeningContext: parsed['listeningContext']?.toString() ??
              'Late night relaxing or travel playlist.',
          similarArtists: (parsed['similarArtists'] as List?)
                  ?.map((e) => e.toString())
                  .toList() ??
              [song.artist],
        );
        _insightCache[cacheKey] = insight;
        return insight;
      }
    }

    final fallback = SongAiInsight.fallback(song);
    _insightCache[cacheKey] = fallback;
    return fallback;
  }

